test "validated unit punctuation stays literal in YAML and exact PromQL selectors" {
    const a = std.testing.allocator;
    const yaml = try renderServices(a, &.{"worker_queue@east:1-2.service"});
    defer a.free(yaml);
    try expectContains(yaml, "service: 'worker_queue@east:1-2.service'");
    try expectContains(yaml, "name=\"worker_queue@east:1-2.service\"");
    for ([_][]const u8{ "bad'unit.service", "bad\"unit.service", "bad\\unit.service", "bad\nunit.service", "bad unit.service", "x.*.service", "../x.service", "$(id).service", "x.timer" }) |invalid| {
        try std.testing.expectError(error.InvalidService, renderServices(a, &.{ "valid.service", invalid }));
    }
    var quoted: std.Io.Writer.Allocating = .init(a);
    defer quoted.deinit();
    try yamlString(&quoted.writer, "worker's state: {{ $value }}");
    try std.testing.expectEqualStrings("'worker''s state: {{ $value }}'", quoted.written());
}

test "VictoriaLogs rules use exact severity stats filtering and explicit rolling windows" {
    const a = std.testing.allocator;
    const first = try renderLogs(a);
    defer a.free(first);
    const second = try renderLogs(a);
    defer a.free(second);
    try std.testing.expectEqualStrings(first, second);
    try expectContains(first, "type: vlogs\n    interval: 1m\n");
    try std.testing.expectEqual(@as(usize, 2), std.mem.count(u8, first, "      - alert: "));
    const errors = try ruleBlock(first, "ErrorBurst");
    try expectContains(errors, "_time:5m level:in(error) | stats by (service) count() as errors | filter errors:>=5\n");
    try expectContains(errors, "severity: 'warning'");
    const critical = try ruleBlock(first, "CriticalLogEvent");
    try expectContains(critical, "_time:1m level:in(critical,fatal) | stats by (service) count() as events | filter events:>=1\n");
    try expectContains(critical, "severity: 'critical'");
    try std.testing.expectEqual(@as(usize, 2), std.mem.count(u8, first, "source: 'victorialogs'"));
    try std.testing.expect(std.mem.indexOf(u8, first, "        for:") == null);
    for ([_][]const u8{ "_msg", "row_any", "request_id", "duration_ms", "{{ query" }) |sensitive| {
        try std.testing.expect(std.mem.indexOf(u8, first, sensitive) == null);
    }
    for ([_][]const u8{ errors, critical }) |block| {
        try expectContains(block, "{{ $labels.service }}");
        try expectContains(block, "{{ $value }}");
    }
}
